        BEGIN
            DBMS_RLS.ADD_POLICY('APP_OWNER','SALES_ORDER_LINE',  'POL_LINE_TENANT',    'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
