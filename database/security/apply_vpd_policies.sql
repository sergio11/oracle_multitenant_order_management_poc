--=====================================================================
-- apply_vpd_policies.sql
--
-- Applies DBMS_RLS (Virtual Private Database) policies to all
-- tenant-aware tables (SRS 14, 93).
--
-- Uses pkg_vpd.tenant_predicate as the predicate function. Each policy
-- appends "tenant_id = <APP_CTX.TENANT_ID>" automatically to queries,
-- providing defense in depth on top of application-level tenant scoping.
--
-- Run as APP_OWNER after V011 migration + package deployment:
--   sqlplus app_owner/<pwd>@//localhost:1521/pdb_oltp @database/security/apply_vpd_policies.sql
--
-- NOTE: Reflects the exact policy set that migrations V011 + V014 + V015
-- create (13 base tables + idempotency key + 2 reporting MVs), kept in
-- sync with database/security/verify_vpd_policies.sql (16/16).
-- Closure fix (S5): earlier revisions asserted only the 14 non-MV
-- policies, so running this script as a repair after an MV rebuild
-- reported success while reporting stayed cross-tenant open.
--
-- H1 (exception safety): the historical shape of this script was
-- "drop every policy, then add every policy". A failure in the ADD
-- pass left the tables without tenant isolation (fail-open) until an
-- operator re-ran the script. The ADD pass below therefore runs in ONE
-- block whose WHEN OTHERS handler re-runs ALL adds (each add in its own
-- tolerant sub-block, so already-present policies raise ORA-28105
-- harmlessly) before RE-RAISING the original error: either the script
-- succeeds with the full policy set, or it fails loudly with as many
-- policies restored as possible - never silently unprotected.
--=====================================================================

-- Ensure all policies are dropped first (idempotent re-runs).
-- Each DROP_POLICY has its OWN exception handler: with a single
-- WHEN OTHERS wrapping all statements, a failure on the first drop
-- would skip every subsequent drop and the ADD block would then fail
-- with ORA-28105 (policy already exists).
BEGIN
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','CUSTOMER','POL_CUSTOMER_TENANT');          EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','CUSTOMER_ADDRESS','POL_ADDR_TENANT');      EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','CUSTOMER_ACCOUNT','POL_ACCT_TENANT');      EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','PRODUCT_CATEGORY','POL_CATEGORY_TENANT');  EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','PRODUCT','POL_PRODUCT_TENANT');            EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','WAREHOUSE','POL_WAREHOUSE_TENANT');        EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','INVENTORY','POL_INVENTORY_TENANT');        EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','SALES_ORDER','POL_ORDER_TENANT');          EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','SALES_ORDER_LINE','POL_LINE_TENANT');      EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','ORDER_STATUS_HISTORY','POL_HISTORY_TENANT'); EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','PAYMENT','POL_PAYMENT_TENANT');            EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','OUTBOX_EVENT','POL_OUTBOX_TENANT');        EXCEPTION WHEN OTHERS THEN NULL; END;
    -- IDEMPOTENCY_KEY table exists only after V012; ignore if absent
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','IDEMPOTENCY_KEY','POL_IDEMP_TENANT');      EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','AUDIT_EVENT','POL_AUDIT_TENANT');          EXCEPTION WHEN OTHERS THEN NULL; END;
    -- Reporting MVs exist only after V013; ignore if absent
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','MV_ORDER_DAILY_SUMMARY','POL_MV_ORDER_TENANT');   EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN DBMS_RLS.DROP_POLICY('APP_OWNER','MV_PRODUCT_SALES_SUMMARY','POL_MV_PRODUCT_TENANT'); EXCEPTION WHEN OTHERS THEN NULL; END;
END;
/

--=====================================================================
-- Add static policies (statement_type 'SELECT,INSERT,UPDATE,DELETE')
-- Compensation: if ANY add below fails, every add is re-attempted in
-- the handler (tolerating ORA-28105 for the ones already restored)
-- and the original error is re-raised - see header.
--=====================================================================
BEGIN
    DBMS_RLS.ADD_POLICY('APP_OWNER','CUSTOMER',          'POL_CUSTOMER_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','CUSTOMER_ADDRESS',  'POL_ADDR_TENANT',    'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','CUSTOMER_ACCOUNT',  'POL_ACCT_TENANT',    'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','PRODUCT_CATEGORY',  'POL_CATEGORY_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','PRODUCT',           'POL_PRODUCT_TENANT', 'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','WAREHOUSE',         'POL_WAREHOUSE_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','INVENTORY',         'POL_INVENTORY_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','SALES_ORDER',       'POL_ORDER_TENANT',   'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','SALES_ORDER_LINE',  'POL_LINE_TENANT',    'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','ORDER_STATUS_HISTORY','POL_HISTORY_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','PAYMENT',           'POL_PAYMENT_TENANT', 'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','OUTBOX_EVENT',      'POL_OUTBOX_TENANT',  'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','IDEMPOTENCY_KEY','POL_IDEMP_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','AUDIT_EVENT','POL_AUDIT_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
    -- Reporting MV policies are SELECT-only (same as V014).
    DBMS_RLS.ADD_POLICY('APP_OWNER','MV_ORDER_DAILY_SUMMARY','POL_MV_ORDER_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT',FALSE);
    DBMS_RLS.ADD_POLICY('APP_OWNER','MV_PRODUCT_SALES_SUMMARY','POL_MV_PRODUCT_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT',FALSE);
EXCEPTION
    WHEN OTHERS THEN
        -- COMPENSATION: restore the full policy set (tolerating
        -- ORA-28105 for policies that are already back), then surface
        -- the original failure so the caller sees a loud error.
        BEGIN
            DBMS_RLS.ADD_POLICY('APP_OWNER','CUSTOMER',          'POL_CUSTOMER_TENANT','APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
        EXCEPTION WHEN OTHERS THEN NULL; END;
        BEGIN
            DBMS_RLS.ADD_POLICY('APP_OWNER','CUSTOMER_ADDRESS',  'POL_ADDR_TENANT',    'APP_OWNER','PKG_VPD.TENANT_PREDICATE','SELECT,INSERT,UPDATE,DELETE',TRUE);
        EXCEPTION WHEN OTHERS THEN NULL; END;
        BEGIN
